// Generates src/styles/*.css from the Figma variables export.
// Run: pnpm tokens
//
// Inputs:
//   design/tokens/figma-variables.json   Figma REST export (W3C-ish $value/$type, aliases as {name})
//   design/tokens/figma-composites.json  alpha/shadow colors the export omits (color + opacity composites)
//
// Outputs (src/styles/):
//   primitives.css     raw values: palette, fonts, sizes, spacing, radius, opacity, widths
//   themes.css         theme switches as data-* attributes on <html>
//   color-mode.css     semantic colors: :root (Light) and .dark (Dark)
//   tailwind-theme.css @theme inline mappings so tokens become Tailwind utilities
//   tokens.css         imports all of the above

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const outDir = join(root, "src/styles")
const exportJson = JSON.parse(readFileSync(join(root, "design/tokens/figma-variables.json"), "utf8"))
const composites = JSON.parse(readFileSync(join(root, "design/tokens/figma-composites.json"), "utf8"))

mkdirSync(outDir, { recursive: true })

const HEADER = "/* Generated by scripts/build-tokens.mjs from the Figma variables export. Do not edit by hand. */\n"

// ---------------------------------------------------------------------------
// Helpers

const collections = Object.fromEntries(exportJson.map((entry) => Object.entries(entry)[0]))

const slug = (s) =>
  String(s)
    .trim()
    .toLowerCase()
    .replace(/\+/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")

/** Flatten a mode tree into [[path[], token], ...]. */
function leaves(tree, path = []) {
  if (tree && tree.$type !== undefined) return [[path, tree]]
  return Object.entries(tree).flatMap(([k, v]) => leaves(v, [...path, k]))
}

function modes(name) {
  const c = collections[name]
  if (!c) throw new Error(`Missing collection "${name}" in export`)
  return c.modes
}

const firstMode = (name) => Object.values(modes(name))[0]

const px = (n) => (n === 0 ? "0" : `${n}px`)

/** `{Group.leaf}` / `{leaf}` alias → "leaf" (leaf names are unique per collection). */
function aliasTarget(value) {
  const m = /^\{(.+)\}$/.exec(value)
  if (!m) return null
  const leaf = m[1].split(".").pop()
  return leaf
}

/** "#rrggbb" → "oklch(L C H)" like shadcn (achromatic → C 0 H 0). 4 decimals keep every color within 1/255 of the Figma hex. */
function hexToOklch(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex)
  if (!m) throw new Error(`Unexpected color "${hex}"`)
  const [r, g, b] = [0, 2, 4]
    .map((i) => parseInt(m[1].slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))

  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const mm = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)

  const L = 0.2104542553 * l + 0.793617785 * mm - 0.0040720468 * s
  const A = 1.9779984951 * l - 2.428592205 * mm + 0.4505937099 * s
  const B = 0.0259040371 * l + 0.7827717662 * mm - 0.808675766 * s

  const C = Math.hypot(A, B)
  const H = (Math.atan2(B, A) * 180) / Math.PI
  const round = (n) => +n.toFixed(4)
  if (C < 0.0005) return `oklch(${round(L)} 0 0)`
  return `oklch(${round(L)} ${round(C)} ${round(H < 0 ? H + 360 : H)})`
}

const block = (selector, lines) => `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`

const FONT_WEIGHTS = { Light: 300, Regular: 400, Medium: 500, Semibold: 600, Bold: 700, Black: 900 }

const FONT_FALLBACK = {
  Inter: "ui-sans-serif, system-ui, sans-serif",
  Roboto: "ui-sans-serif, system-ui, sans-serif",
  "Playfair Display": "ui-serif, Georgia, serif",
  Merriweather: "ui-serif, Georgia, serif",
  "Ms Madi": "cursive",
}

// ---------------------------------------------------------------------------
// primitives.css

const primitives = []

// Palette
const paletteLines = leaves(firstMode("Default Colors")).map(([path, t]) => `--${slug(path.at(-1))}: ${hexToOklch(t.$value)};`)
primitives.push("/* Default Colors — raw palette (OKLCH, converted from Figma hex) */\n" + block(":root", paletteLines))

// Font families
const fontLines = leaves(firstMode("Fonts")).map(([path, t]) => {
  const family = t.$value
  return `--font-family-${slug(path.at(-1))}: "${family}", ${FONT_FALLBACK[family] ?? "sans-serif"};`
})
primitives.push("/* Fonts */\n" + block(":root", fontLines))

// Font size
const sizeLines = leaves(firstMode("Font Size")).map(([path, t]) => `--font-size-${slug(path.at(-1))}: ${px(t.$value)};`)
primitives.push("/* Font Size */\n" + block(":root", sizeLines))

// Font weight (Figma stores style names; map to numeric weights)
const weightLines = leaves(modes("Font Weight").Default).map(
  ([path]) => `--weight-${slug(path.at(-1))}: ${FONT_WEIGHTS[path.at(-1)]};`,
)
primitives.push("/* Font Weight */\n" + block(":root", weightLines))

// Spacing
const spaceLines = leaves(firstMode("Spacing")).map(([path, t]) => {
  const key = String(path.at(-1)).startsWith("-") ? `n${String(path.at(-1)).slice(1)}` : slug(path.at(-1))
  return `--space-${key}: ${px(t.$value)};`
})
primitives.push("/* Spacing — Base Spacing (negative values as --space-nX) */\n" + block(":root", spaceLines))

// Opacity
const opacityLines = leaves(firstMode("Opacity")).map(([path, t]) => `--opacity-${slug(path.at(-1))}: ${t.$value / 100};`)
primitives.push("/* Opacity */\n" + block(":root", opacityLines))

// Max width
const widthLines = leaves(firstMode("Max Width")).map(([path, t]) => `--max-width-${slug(path.at(-1))}: ${px(t.$value)};`)
primitives.push("/* Max Width */\n" + block(":root", widthLines))

writeFileSync(join(outDir, "primitives.css"), HEADER + "\n" + primitives.join("\n"))

// ---------------------------------------------------------------------------
// themes.css — one data-* attribute per Figma theme collection.
// The first Figma mode is the default and lives on :root.

const themeSections = []

/**
 * @param {string} collection Figma collection name
 * @param {string} attr       data attribute (without "data-")
 * @param {(path: string[], token: object) => string} line  CSS declaration for one token
 */
function themeCollection(collection, attr, line) {
  const entries = Object.entries(modes(collection))
  const out = [`/* ${collection} — data-${attr} on <html>: ${entries.map(([m]) => `"${slug(m)}"`).join(" | ")} */`]
  entries.forEach(([mode, tree], i) => {
    const selector = i === 0 ? `:root,\n:root[data-${attr}="${slug(mode)}"]` : `:root[data-${attr}="${slug(mode)}"]`
    out.push(block(selector, leaves(tree).map(([path, t]) => line(path, t)).filter(Boolean)))
  })
  themeSections.push(out.join("\n"))
}

const colorAlias = (path, t) => `--${slug(path.at(-1))}: var(--${slug(aliasTarget(t.$value))});`

themeCollection("Primary Colors", "primary", colorAlias)
themeCollection("Gray Theme", "gray", colorAlias)
themeCollection("Radius", "radius", (path, t) => `--r-${slug(path.at(-1)).replace(/^r-/, "")}: ${px(t.$value)};`)
themeCollection("Font Line Height", "leading", (path, t) => `--line-height-${slug(path.at(-1))}: ${px(t.$value)};`)
themeCollection("Letter Spacing", "tracking", (_path, t) => `--letter-spacing: ${px(t.$value)};`)
themeCollection("Stroke", "stroke", (_path, t) => `--stroke-width: ${px(t.$value)};`)
themeCollection("Default Font", "font", (_path, t) => `--font-family-default: var(--font-family-${slug(aliasTarget(t.$value))});`)
themeCollection("Display Font", "display-font", (_path, t) => `--font-family-display: var(--font-family-${slug(aliasTarget(t.$value))});`)
// Figma's Font Weight modes swap style names ("Bold" ↔ "Bold Italic"); in CSS that is just font-style.
themeCollection("Font Weight", "font-style", (path, t) =>
  path.at(-1) === "Regular" ? `--font-style: ${/Italic/.test(t.$value) ? "italic" : "normal"};` : null,
)

writeFileSync(join(outDir, "themes.css"), HEADER + "\n" + themeSections.join("\n"))

// ---------------------------------------------------------------------------
// color-mode.css — semantic colors per Light/Dark

const colorModes = modes("Color Mode")

function colorModeLines(modeName) {
  const lines = []
  for (const [path, t] of leaves(colorModes[modeName])) {
    const name = slug(path.at(-1))
    const group = path[0]

    if (t.$value !== undefined) {
      lines.push(`--${name}: var(--${slug(aliasTarget(t.$value))});`)
      continue
    }

    // Composite (color + opacity) values missing from the export
    const shadow = composites.shadows[name]
    if (shadow) {
      const [base, pct] = shadow[modeName]
      lines.push(`--${name}: color-mix(in oklab, var(--${base}) ${pct}%, transparent);`)
      continue
    }

    const alpha = /-alpha-(\d+)$/.exec(name)
    const base = composites.alphaBase[group]
    if (alpha && base) {
      const pct = composites.alphaExceptions[name]?.[modeName] ?? Number(alpha[1])
      lines.push(`--${name}: color-mix(in oklab, var(--${base}) ${pct}%, transparent);`)
      continue
    }

    throw new Error(`No value for Color Mode token "${path.join("/")}" (${modeName})`)
  }
  return lines
}

const colorModeNames = Object.keys(colorModes)
writeFileSync(
  join(outDir, "color-mode.css"),
  HEADER +
    "\n/* Color Mode — Light on :root, Dark on .dark (matches shadcn's dark variant) */\n" +
    block(":root", colorModeLines(colorModeNames[0])) +
    "\n" +
    block(".dark", colorModeLines(colorModeNames[1])),
)

// ---------------------------------------------------------------------------
// tailwind-theme.css — expose tokens as Tailwind utilities.
// Spacing and opacity are left to Tailwind's defaults: its 4px spacing scale and
// percentage opacity scale already match the Figma values (p-4 = 16px, opacity-50).

const theme = []

theme.push("  /* Colors: bg-primary-500, text-base-900, border-danger-alpha-20, shadow-shadow-primary ... */")
for (const [path] of leaves(colorModes[colorModeNames[0]])) {
  const name = slug(path.at(-1))
  theme.push(`  --color-${name}: var(--${name});`)
}

theme.push("\n  /* Fonts: font-default, font-display */")
theme.push("  --font-default: var(--font-family-default);")
theme.push("  --font-display: var(--font-family-display);")

theme.push("\n  /* Font size: text-16, text-24 ... */")
for (const [path] of leaves(firstMode("Font Size"))) theme.push(`  --text-${slug(path.at(-1))}: var(--font-size-${slug(path.at(-1))});`)

theme.push("\n  /* Line height: leading-24 ... (follows data-leading) */")
for (const [path] of leaves(firstMode("Font Line Height"))) theme.push(`  --leading-${slug(path.at(-1))}: var(--line-height-${slug(path.at(-1))});`)

theme.push("\n  /* Letter spacing: tracking-default (follows data-tracking) */")
theme.push("  --tracking-default: var(--letter-spacing);")

theme.push("\n  /* Radius: rounded-r12 ... (follows data-radius) */")
for (const [path] of leaves(firstMode("Radius"))) {
  const n = slug(path.at(-1)).replace(/^r-/, "")
  theme.push(`  --radius-r${n}: var(--r-${n});`)
}

theme.push("\n  /* Max width: max-w-desktop, max-w-tablet, max-w-mobile */")
for (const [path] of leaves(firstMode("Max Width"))) theme.push(`  --container-${slug(path.at(-1))}: var(--max-width-${slug(path.at(-1))});`)

writeFileSync(join(outDir, "tailwind-theme.css"), HEADER + "\n@theme inline {\n" + theme.join("\n") + "\n}\n")

// ---------------------------------------------------------------------------
// src/lib/design-tokens.ts — token keys cn() must know about. Numeric font sizes
// (text-16) are otherwise read as colors and dropped next to text-base-900, and
// radii (rounded-r20) are unknown, so they don't replace a base rounded-xl.

const fontSizeKeys = leaves(firstMode("Font Size")).map(([path]) => slug(path.at(-1)))
const radiusKeys = leaves(firstMode("Radius")).map(([path]) => "r" + slug(path.at(-1)).replace(/^r-/, ""))
writeFileSync(
  join(root, "src/lib/design-tokens.ts"),
  "// Generated by scripts/build-tokens.mjs from the Figma variables export. Do not edit by hand.\n\n" +
    `export const fontSizes = ${JSON.stringify(fontSizeKeys)} as const\n` +
    `export const radii = ${JSON.stringify(radiusKeys)} as const\n`,
)

// ---------------------------------------------------------------------------
// tokens.css — single entry point

writeFileSync(
  join(outDir, "tokens.css"),
  HEADER +
    '\n@import "./primitives.css";\n@import "./themes.css";\n@import "./color-mode.css";\n@import "./tailwind-theme.css";\n',
)

console.log("Tokens written to src/styles/")
